"""Backtest all targets on synthetic data (no DB needed) → markdown metrics report.

Usage (from backend/):  python -m scripts.eval_forecasts [--days 400] [--out ../docs/metrics_forecasts.md]
Gate 3: demand MAPE <= 3%; price MAE 400-600 INR/MWh (stretch 300).
"""

from __future__ import annotations

import argparse
from datetime import date, timedelta
from pathlib import Path

from app.adapters.synthetic import SyntheticAdapter
from app.config import load_config
from app.domain.enums import ForecastTarget
from app.forecasting.backtest import rolling_origin_backtest
from app.forecasting.features import points_to_frame
from app.logging_setup import configure_logging, get_logger

log = get_logger(__name__)

SERIES = {
    ForecastTarget.DEMAND: ("demand", "demand_mw", 42),
    ForecastTarget.PRICE: ("price", "price_dam_inr_mwh", 43),
    ForecastTarget.INFLOW: ("inflow", "inflow_mwh", 44),
}


def synthetic_history(target: ForecastTarget, days: int, end: date):
    name, series_id, seed = SERIES[target]
    adapter = SyntheticAdapter(name, series_id, seed)
    points = []
    d = end - timedelta(days=days)
    while d < end:
        points.extend(adapter.generate_day(d))
        d += timedelta(days=1)
    return points_to_frame(points)


def main() -> None:
    configure_logging()
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--days", type=int, default=400)
    parser.add_argument("--out", type=str, default="../docs/metrics_forecasts.md")
    parser.add_argument("--end", type=str, default="2026-07-01")
    args = parser.parse_args()

    cfg = load_config("forecasting")
    end = date.fromisoformat(args.end)
    lines = [
        "# Forecast backtest metrics (synthetic data)",
        "",
        f"Rolling-origin backtest, {args.days} days ending {end}. Auto-generated by",
        "`python -m scripts.eval_forecasts` — regenerate after model/config changes.",
        "",
        "| target | model | folds | MAPE % | MAE | pinball p10 | pinball p90 | target |",
        "|---|---|---|---|---|---|---|---|",
    ]
    for target in ForecastTarget:
        history = synthetic_history(target, args.days, end)
        m = rolling_origin_backtest(history, None, target, cfg)
        tcfg = cfg["targets"][target.value]
        goal = (
            f"MAPE <= {tcfg['target_mape_pct']}%"
            if "target_mape_pct" in tcfg
            else f"MAE <= {tcfg.get('target_mae_inr_mwh', 'n/a')}"
        )
        lines.append(
            f"| {target.value} | {m.model_name} | {m.n_folds} "
            f"| {m.mape_pct:.2f} | {m.mae:.1f} | {m.pinball_p10:.1f} | {m.pinball_p90:.1f} | {goal} |"
        )
        log.info(
            "backtested", target=target.value, mape=round(m.mape_pct or -1, 2), mae=round(m.mae or -1, 1)
        )

    out = Path(args.out)
    out.parent.mkdir(parents=True, exist_ok=True)
    out.write_text("\n".join(lines) + "\n", encoding="utf-8")
    print("\n".join(lines))
    print(f"\nwritten: {out}")


if __name__ == "__main__":
    main()
